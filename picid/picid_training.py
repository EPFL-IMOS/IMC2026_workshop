    local_artifacts = workshop_root / "artifacts"
    local_cache = workshop_root / ".cache" / "picid"
    path_environment = {
        "PROJECT_ROOT": workshop_root,
        "TAB_PHM_ROOT_DIR": workshop_root,
        "TAB_PHM_CONFIG_PATH": picid_package / "configs",
        "TAB_PHM_OUTPUT_DIR": local_artifacts,
        "TAB_PHM_DATA_DIR": workshop_root / "data",
        "TAB_PHM_DATASET_DIR": workshop_root / "data",
        "TAB_PHM_CACHE_PATH": local_cache,
        "TAB_PHM_CACHE_DIR": local_cache,
        "TAB_PHM_LOG_DIR": local_artifacts / "logs",
        "TAB_PHM_PLOT_DIR": local_artifacts / "plots",
        "TAB_PHM_EVAL_DETAILS": local_artifacts / "eval_details",
        "TAB_PHM_MODEL_WORKDIR": local_artifacts / "model_workdir",
        "TAB_PHM_CKPT_DIR": local_artifacts / "checkpoints",
        "TAB_PHM_ARTIFACTS_DIR": local_artifacts,
        "TAB_PHM_MODEL_CACHE_DIR": local_artifacts / "model_cache",
        "TAB_PHM_SAVE_DIR": local_artifacts / "saved",
    }
    for variable, path in path_environment.items():
        os.environ.setdefault(variable, str(path))


