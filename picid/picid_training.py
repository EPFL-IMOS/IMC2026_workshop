def configure_picid_paths(workshop_root: Path = WORKSHOP_ROOT) -> None:
    """Use PICID's installed configs while keeping outputs in the workshop."""

    picid_spec = find_spec("picid")
    if picid_spec is None or not picid_spec.submodule_search_locations:
        raise RuntimeError("PICID is not installed. Run `uv sync` first.")

