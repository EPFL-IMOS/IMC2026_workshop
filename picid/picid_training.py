class FitPredictBayesianRidgeWrapper(AbstractFitPredictWrapper):
    """Run scikit-learn's Bayesian ridge regressor through PICID's adapter API."""

    def __init__(
        self,
        task_type: str,
        *,
        model_cache_path: str | Path | None = None,
        compute_score: bool = True,
        max_iter: int = 300,
        tol: float = 1e-3,
        **kwargs: Any,
    ) -> None:
        if task_type not in REGRESSION_TASKS:
            raise ValueError(
                "FitPredictBayesianRidgeWrapper supports only regression tasks; "
                f"received {task_type!r}."
            )

        self.task_type = task_type
        self.model_cache_path = (
            WORKSHOP_ROOT / "artifacts" / "model_cache" / "bayesian_ridge"
            if model_cache_path is None
            else Path(model_cache_path)
        )
        backbone = BayesianRidge(
            compute_score=compute_score,
            max_iter=max_iter,
            tol=tol,
        )
        super().__init__(backbone=backbone, task_type=task_type, **kwargs)

    def _call_fit(self, X: torch.Tensor, y: torch.Tensor) -> None:
        """Convert PICID tensors to the one-target arrays expected by sklearn."""

        features = X.detach().cpu().numpy().astype(np.float64, copy=False)
        targets = y.detach().cpu().numpy().reshape(-1).astype(np.float64, copy=False)
        if not np.isfinite(features).all() or not np.isfinite(targets).all():
            raise ValueError("Bayesian ridge received non-finite training values.")
        # Accelerate-backed NumPy may emit spurious overflow warnings from dot even
        # when sklearn's fitted coefficients and evidence scores remain finite.
        with np.errstate(divide="ignore", over="ignore", invalid="ignore"):
            self.backbone.fit(features, targets)
        if not np.isfinite(self.backbone.coef_).all():
            raise FloatingPointError("Bayesian ridge fitted non-finite coefficients.")

    def _call_predict(self, X: torch.Tensor) -> torch.Tensor:
        """Return point predictions in PICID's tensor format."""

        features = X.detach().cpu().numpy().astype(np.float64, copy=False)
        with np.errstate(divide="ignore", over="ignore", invalid="ignore"):
            predictions = self.backbone.predict(features)
        if not np.isfinite(predictions).all():
            raise FloatingPointError("Bayesian ridge returned non-finite predictions.")
        predictions = predictions.astype(np.float32, copy=False)
        return torch.from_numpy(predictions)

    def predict_distribution(
        self,
        X: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Expose Bayesian mean and standard deviation for later diagnostics."""

        features = X.detach().cpu().numpy().astype(np.float64, copy=False)
        with np.errstate(divide="ignore", over="ignore", invalid="ignore"):
            mean, standard_deviation = self.backbone.predict(
                features,
                return_std=True,
            )
        if not np.isfinite(mean).all() or not np.isfinite(standard_deviation).all():
            raise FloatingPointError(
                "Bayesian ridge returned a non-finite predictive distribution."
            )
        return (
            torch.from_numpy(mean.astype(np.float32, copy=False)).reshape(-1, 1),
            torch.from_numpy(
                standard_deviation.astype(np.float32, copy=False)
            ).reshape(-1, 1),
        )

    def _model_path(self, task_id: str | int) -> Path:
        if task_id is None:
            raise ValueError("A PICID task id is required for model caching.")
        return self.model_cache_path / f"{task_id}.joblib"

    def serialize_model(self, task_id: str | int) -> str:
        """Persist the fitted estimator for PICID's validation/test reload."""

        model_path = self._model_path(task_id)
        model_path.parent.mkdir(parents=True, exist_ok=True)
        joblib.dump(self.backbone, model_path)
        return str(model_path)

    def load_model(self, task_id: str | int) -> BayesianRidge:
        """Restore the estimator selected by PICID's task id."""

        self.backbone = joblib.load(self._model_path(task_id))
        return self.backbone

    @property
    def allows_multi_target(self) -> bool:
        """BayesianRidge accepts one RUL target at a time."""

        return False


class FitPredictDecisionTreeWrapper(AbstractFitPredictWrapper):
    """Run scikit-learn's decision-tree regressor through PICID's adapter API."""

    def __init__(
        self,
        task_type: str,
        *,
        model_cache_path: str | Path | None = None,
        max_depth: int | None = 6,
        min_samples_leaf: int = 20,
        random_state: int = SEED,
        **kwargs: Any,
    ) -> None:
        if task_type not in REGRESSION_TASKS:
            raise ValueError(
                "FitPredictDecisionTreeWrapper supports only regression tasks; "
                f"received {task_type!r}."
            )

        self.task_type = task_type
        self.model_cache_path = (
            WORKSHOP_ROOT / "artifacts" / "model_cache" / "decision_tree_24_step"
            if model_cache_path is None
            else Path(model_cache_path)
        )
        backbone = DecisionTreeRegressor(
            max_depth=max_depth,
            min_samples_leaf=min_samples_leaf,
            random_state=random_state,
        )
        super().__init__(backbone=backbone, task_type=task_type, **kwargs)

    def _call_fit(self, X: torch.Tensor, y: torch.Tensor) -> None:
        """Convert PICID tensors to the one-target arrays expected by sklearn."""

        features = X.detach().cpu().numpy()
        targets = y.detach().cpu().numpy().reshape(-1)
        if not np.isfinite(features).all() or not np.isfinite(targets).all():
            raise ValueError("Decision tree received non-finite training values.")
        self.backbone.fit(features, targets)

    def _call_predict(self, X: torch.Tensor) -> torch.Tensor:
        """Return decision-tree predictions in PICID's tensor format."""

        features = X.detach().cpu().numpy()
        predictions = self.backbone.predict(features)
        if not np.isfinite(predictions).all():
            raise FloatingPointError("Decision tree returned non-finite predictions.")
        return torch.from_numpy(predictions.astype(np.float32, copy=False))

    def _model_path(self, task_id: str | int) -> Path:
        if task_id is None:
            raise ValueError("A PICID task id is required for model caching.")
        return self.model_cache_path / f"{task_id}.joblib"

    def serialize_model(self, task_id: str | int) -> str:
        """Persist the fitted estimator for PICID's validation/test reload."""

        model_path = self._model_path(task_id)
        model_path.parent.mkdir(parents=True, exist_ok=True)
        joblib.dump(self.backbone, model_path)
        return str(model_path)

    def load_model(self, task_id: str | int) -> DecisionTreeRegressor:
        """Restore the estimator selected by PICID's task id."""

        self.backbone = joblib.load(self._model_path(task_id))
        return self.backbone

    @property
    def allows_multi_target(self) -> bool:
        """DecisionTreeRegressor is kept to one RUL target in this tutorial."""

        return False


