def _best_checkpoint(checkpoint_dir: Path) -> Path:
    """Resolve the lowest-validation-loss checkpoint in one branch directory."""

    checkpoint_paths = sorted(Path(checkpoint_dir).glob("*.ckpt"))
    if not checkpoint_paths:
        raise FileNotFoundError(f"No checkpoint found in {checkpoint_dir}")

    def validation_loss(path: Path) -> float:
        marker = "val_loss"
        try:
            return float(path.stem.split(marker, maxsplit=1)[1])
        except (IndexError, ValueError):
            return float("inf")

    return min(checkpoint_paths, key=validation_loss)


def _load_backbone_state(model: torch.nn.Module, checkpoint_path: Path) -> None:
    """Load the backbone portion of a PICID Lightning checkpoint in place."""

    checkpoint = torch.load(
        checkpoint_path,
        map_location="cpu",
        weights_only=False,
    )
    prefix = "backbone.backbone."
    backbone_state = {
        key.removeprefix(prefix): value
        for key, value in checkpoint["state_dict"].items()
        if key.startswith(prefix)
    }
    if not backbone_state:
        raise ValueError(
            f"Checkpoint {checkpoint_path} contains no '{prefix}*' tensors."
        )
    model.load_state_dict(backbone_state, strict=True)


def _prediction_summary(
    windows: pd.DataFrame,
    group_keys: list[str],
    constant_prediction: float,
) -> pd.DataFrame:
    """Summarize model dynamics and skill relative to one constant baseline."""

    rows: list[dict[str, Any]] = []
    model_columns = {
        "XGBoost": "xgboost_prediction",
        "Bayesian ridge": "bayesian_prediction",
        "XGBoost (24-step)": "xgboost_24_step_prediction",
        "Bayesian ridge (24-step)": "bayesian_24_step_prediction",
        "Decision tree (24-step)": "decision_tree_24_step_prediction",
        "MLP": "mlp_prediction",
        "custom U-Net": "custom_unet_prediction",
    }
    for group_values, group in windows.groupby(group_keys, sort=False):
        if not isinstance(group_values, tuple):
            group_values = (group_values,)
        group_metadata = dict(zip(group_keys, group_values, strict=True))
        targets = group["target"].to_numpy(dtype=float)
        constant_errors = targets - constant_prediction
        constant_mse = float(np.mean(np.square(constant_errors)))
        constant_mae = float(np.mean(np.abs(constant_errors)))
        target_std = float(np.std(targets))

        for model_name, prediction_column in model_columns.items():
            predictions = group[prediction_column].to_numpy(dtype=float)
            errors = predictions - targets
            prediction_std = float(np.std(predictions))
            correlation = (
                float(np.corrcoef(predictions, targets)[0, 1])
                if prediction_std > 1e-12 and target_std > 1e-12
                else float("nan")
            )
            mse = float(np.mean(np.square(errors)))
            rows.append(
                {
                    **group_metadata,
                    "model": model_name,
                    "n_windows": len(group),
                    "mse": mse,
                    "mae": float(np.mean(np.abs(errors))),
                    "bias": float(np.mean(errors)),
                    "prediction_std": prediction_std,
                    "target_std": target_std,
                    "std_ratio": (
                        prediction_std / target_std if target_std > 0.0 else np.nan
                    ),
                    "correlation": correlation,
                    "constant_mse": constant_mse,
                    "constant_mae": constant_mae,
                    "skill_vs_constant": (
                        1.0 - mse / constant_mse if constant_mse > 0.0 else np.nan
                    ),
                    "beats_constant": mse < constant_mse,
                }
            )
    return pd.DataFrame(rows)


def build_checkpoint_unroll(
    *,
    prepared: PreparedExperiment,
    run: TrainingRun,
    custom_unet_model: torch.nn.Module,
    stride: int,
) -> CheckpointUnroll:
    """Reconstruct aligned predictions from all seven persisted models."""

    input_channels = prepared.deep_shapes[0][-1]
    mlp_model = MLP(
        {
            "seq_len": prepared.seq_len,
            "input_channels": input_channels,
            "hidden_dim": 64,
            "num_layers": 2,
        },
        task_type="regression",
        num_targets=1,
    )
    custom_model = deepcopy(custom_unet_model)
    _load_backbone_state(mlp_model, run.mlp_checkpoint_path)
    _load_backbone_state(custom_model, run.custom_unet_checkpoint_path)
    mlp_model.eval()
    custom_model.eval()
    xgboost_model = joblib.load(run.xgboost_model_path)
    bayesian_model = joblib.load(run.bayesian_model_path)
    windowed_xgboost_model = joblib.load(run.windowed_xgboost_model_path)
    windowed_bayesian_model = joblib.load(run.windowed_bayesian_model_path)
    decision_tree_model = joblib.load(run.decision_tree_model_path)

    window_rows: list[dict[str, Any]] = []
    data_dict = prepared.deep_learning_processed.data_dict
    pointwise_data_dict = prepared.fit_predict_processed.data_dict
    windowed_data_dict = prepared.windowed_fit_predict_processed.data_dict
    with torch.inference_mode():
        for split in ("train", "val", "test"):
            unit_names = prepared.unit_names_by_split[split]
            features_by_unit = data_dict[split]["features"]
            targets_by_unit = data_dict[split]["rul"]
            pointwise_features_by_unit = pointwise_data_dict[split]["features"]
            windowed_features_by_unit = windowed_data_dict[split]["features"]
            windowed_targets_by_unit = windowed_data_dict[split]["rul"]
            for (
                unit_name,
                features,
                targets,
                pointwise_features,
                windowed_features,
                windowed_targets,
            ) in zip(
                unit_names,
                features_by_unit,
                targets_by_unit,
                pointwise_features_by_unit,
                windowed_features_by_unit,
                windowed_targets_by_unit,
                strict=True,
            ):
                start_indices = np.arange(
                    0,
                    len(features) - prepared.seq_len + 1,
                    stride,
                )
                feature_windows = np.stack(
                    [
                        features[start : start + prepared.seq_len]
                        for start in start_indices
                    ]
                )
                target_values = np.asarray(targets)[
                    start_indices + prepared.seq_len - 1,
                    0,
                ]
                end_indices = start_indices + prepared.seq_len - 1
                pointwise_features = np.asarray(pointwise_features).squeeze(0)
                windowed_features = np.asarray(windowed_features).squeeze(0)
                windowed_targets = np.asarray(windowed_targets).squeeze(0)[:, 0]
                if len(windowed_features) != len(end_indices):
                    raise ValueError(
                        "PICID's tabularized history is not aligned with the "
                        f"neural windows for {split}/{unit_name}: "
                        f"{len(windowed_features)} != {len(end_indices)}."
                    )
                if not np.allclose(windowed_targets, target_values):
                    raise ValueError(
                        "PICID's tabularized present targets do not match the "
                        f"neural window endpoints for {split}/{unit_name}."
                    )
                xgboost_predictions = xgboost_model.predict(
                    pointwise_features[end_indices]
                ).astype(np.float32, copy=False)
                bayesian_predictions = bayesian_model.predict(
                    pointwise_features[end_indices]
                ).astype(np.float32, copy=False)
                windowed_xgboost_predictions = windowed_xgboost_model.predict(
                    windowed_features
                ).astype(np.float32, copy=False)
                windowed_bayesian_predictions = windowed_bayesian_model.predict(
                    windowed_features
                ).astype(np.float32, copy=False)
                decision_tree_predictions = decision_tree_model.predict(
                    windowed_features
                ).astype(np.float32, copy=False)
                feature_tensor = torch.as_tensor(
                    feature_windows,
                    dtype=torch.float32,
                )
                mlp_predictions = (
                    mlp_model(feature_tensor.transpose(1, 2))
                    .squeeze(-1)
                    .cpu()
                    .numpy()
                )
                custom_predictions = (
                    custom_model(feature_tensor).squeeze(-1).cpu().numpy()
                )
                for (
                    index,
                    target,
                    xgboost_prediction,
                    bayesian_prediction,
                    windowed_xgboost_prediction,
                    windowed_bayesian_prediction,
                    decision_tree_prediction,
                    mlp_prediction,
                    custom_prediction,
                ) in zip(
                    end_indices,
                    target_values,
                    xgboost_predictions,
                    bayesian_predictions,
                    windowed_xgboost_predictions,
                    windowed_bayesian_predictions,
                    decision_tree_predictions,
                    mlp_predictions,
                    custom_predictions,
                    strict=True,
                ):
                    window_rows.append(
                        {
                            "split": split,
                            "unit": unit_name,
                            "time_index": int(index),
                            "target": float(target),
                            "xgboost_prediction": float(xgboost_prediction),
                            "bayesian_prediction": float(bayesian_prediction),
                            "xgboost_24_step_prediction": float(
                                windowed_xgboost_prediction
                            ),
                            "bayesian_24_step_prediction": float(
                                windowed_bayesian_prediction
                            ),
                            "decision_tree_24_step_prediction": float(
                                decision_tree_prediction
                            ),
                            "mlp_prediction": float(mlp_prediction),
                            "custom_unet_prediction": float(custom_prediction),
                        }
                    )

    windows = pd.DataFrame(window_rows)
    constant_prediction = float(
        windows.loc[windows["split"] == "train", "target"].mean()
    )
    windows["constant_prediction"] = constant_prediction
    unit_summary = _prediction_summary(
        windows,
        ["split", "unit"],
        constant_prediction,
    )
    split_summary = _prediction_summary(
        windows,
        ["split"],
        constant_prediction,
    )
    return CheckpointUnroll(
        windows=windows,
        unit_summary=unit_summary,
        split_summary=split_summary,
        constant_prediction=constant_prediction,
        mlp_checkpoint_path=run.mlp_checkpoint_path,
        custom_unet_checkpoint_path=run.custom_unet_checkpoint_path,
    )


def package_training_run(
    *,
    fit_predict_results: list[dict[str, Any]],
    bayesian_fit_predict_results: list[dict[str, Any]],
    windowed_fit_predict_results: list[dict[str, Any]],
    bayesian_windowed_fit_predict_results: list[dict[str, Any]],
    decision_tree_results: list[dict[str, Any]],
    deep_learning_results: list[dict[str, Any]],
    custom_unet_results: list[dict[str, Any]],
    seed: int = SEED,
    deep_learning_epochs: int = DEEP_LEARNING_EPOCHS,
) -> TrainingRun:
    """Combine returned results and resolve both neural-model metric files."""

    result_rows = []
    for model_family, model_name, results in [
        ("XGBoost", "xgboost_fit_predict", fit_predict_results),
        (
            "Bayesian ridge",
            "bayesian_ridge",
            bayesian_fit_predict_results,
        ),
        (
            "XGBoost (24-step)",
            "xgboost_fit_predict_24_step",
            windowed_fit_predict_results,
        ),
        (
            "Bayesian ridge (24-step)",
            "bayesian_ridge_24_step",
            bayesian_windowed_fit_predict_results,
        ),
        (
            "Decision tree (24-step)",
            "decision_tree_24_step",
            decision_tree_results,
        ),
        ("MLP", "mlp", deep_learning_results),
        ("custom U-Net", "small_unet_1d", custom_unet_results),
    ]:
        metrics = results[0] if results else {}
        result_rows.append(
            {
                "family": model_family,
                "model": model_name,
                **metrics,
            }
        )

    trace_version = make_trace_version(
        seed=seed,
        deep_learning_epochs=deep_learning_epochs,
    )
    deep_metrics_path = (
        WORKSHOP_ROOT
        / "artifacts"
        / "saved"
        / "picid_experiment_deep_learning"
        / trace_version
        / "metrics.csv"
    )
    custom_unet_metrics_path = (
        WORKSHOP_ROOT
        / "artifacts"
        / "saved"
        / "picid_experiment_custom_unet"
        / trace_version
        / "metrics.csv"
    )
    for metrics_path in (deep_metrics_path, custom_unet_metrics_path):
        if not metrics_path.exists():
            raise FileNotFoundError(f"Expected CSV logger output at {metrics_path}")

    checkpoint_root = WORKSHOP_ROOT / "artifacts" / "checkpoints" / trace_version
    mlp_checkpoint_path = _best_checkpoint(checkpoint_root / "mlp")
    custom_unet_checkpoint_path = _best_checkpoint(checkpoint_root / "custom_unet")
    model_cache_root = WORKSHOP_ROOT / "artifacts" / "model_cache"
    xgboost_model_path = model_cache_root / "xgboost" / "0.joblib"
    bayesian_model_path = model_cache_root / "bayesian_ridge" / "0.joblib"
    windowed_xgboost_model_path = (
        model_cache_root / "xgboost_24_step" / "0.joblib"
    )
    windowed_bayesian_model_path = (
        model_cache_root / "bayesian_ridge_24_step" / "0.joblib"
    )
    decision_tree_model_path = (
        model_cache_root / "decision_tree_24_step" / "0.joblib"
    )
    for model_path in (
        xgboost_model_path,
        bayesian_model_path,
        windowed_xgboost_model_path,
        windowed_bayesian_model_path,
        decision_tree_model_path,
    ):
        if not model_path.exists():
            raise FileNotFoundError(f"Expected fit/predict model at {model_path}")

    return TrainingRun(
        fit_predict_results=fit_predict_results,
        bayesian_fit_predict_results=bayesian_fit_predict_results,
        windowed_fit_predict_results=windowed_fit_predict_results,
        bayesian_windowed_fit_predict_results=(
            bayesian_windowed_fit_predict_results
        ),
        decision_tree_results=decision_tree_results,
        deep_learning_results=deep_learning_results,
        custom_unet_results=custom_unet_results,
        result_frame=pd.DataFrame(result_rows),
        deep_metrics_path=deep_metrics_path,
        custom_unet_metrics_path=custom_unet_metrics_path,
        mlp_checkpoint_path=mlp_checkpoint_path,
        custom_unet_checkpoint_path=custom_unet_checkpoint_path,
        xgboost_model_path=xgboost_model_path,
        bayesian_model_path=bayesian_model_path,
        windowed_xgboost_model_path=windowed_xgboost_model_path,
        windowed_bayesian_model_path=windowed_bayesian_model_path,
        decision_tree_model_path=decision_tree_model_path,
        trace_version=trace_version,
        deep_learning_epochs=deep_learning_epochs,
    )
