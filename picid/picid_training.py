def summarize_prepared_experiment(
    *,
    experiment: Any,
    unit_frames: dict[str, pd.DataFrame],
    unit_summary: pd.DataFrame,
    unit_names: list[str],
    unit_names_by_split: dict[str, list[str]],
    deep_learning_processed: Any,
    fit_predict_processed: Any,
    windowed_fit_predict_processed: Any,
    seq_len: int,
) -> PreparedExperiment:
    """Collect shape and split-alignment metadata after notebook preprocessing."""

    data_dict = deep_learning_processed.data_dict
    expected_units = set(unit_names)
    assigned_units = [
        unit_name
        for split in ("train", "val", "test")
        for unit_name in unit_names_by_split[split]
    ]
    if len(assigned_units) != len(set(assigned_units)):
        raise ValueError("Each unit must belong to exactly one split.")
    if set(assigned_units) != expected_units:
        raise ValueError(
            "The by-unit split must assign every unit exactly once; "
            f"expected={sorted(expected_units)}, assigned={sorted(assigned_units)}"
        )

    unit_lengths_by_split = {}
    for split, split_data in data_dict.items():
        split_unit_names = unit_names_by_split[split]
        split_features = split_data["features"]
        if len(split_unit_names) != len(split_features):
            raise ValueError(
                f"PICID returned {len(split_features)} units for {split}, but the "
                f"configured by-unit split contains {len(split_unit_names)} names."
            )
        unit_lengths_by_split[split] = {
            unit_name: len(unit_features)
            for unit_name, unit_features in zip(
                split_unit_names,
                split_features,
                strict=True,
            )
        }
    keys = sorted({key for split_data in data_dict.values() for key in split_data})
    payloads = [
        (key, {split: data_dict[split].get(key, []) for split in data_dict})
        for key in keys
    ]
    split_alignment_report = collect_split_alignment_report(payloads)
    deep_shapes = [unit.shape for unit in data_dict["train"]["features"]]
    fit_predict_shapes = [
        unit.shape
        for unit in fit_predict_processed.data_dict["train"]["features"]
    ]
    windowed_fit_predict_shapes = [
        unit.shape
        for unit in windowed_fit_predict_processed.data_dict["train"]["features"]
    ]
    return PreparedExperiment(
        experiment=experiment,
        unit_frames=unit_frames,
        unit_summary=unit_summary,
        unit_names=unit_names,
        unit_names_by_split=unit_names_by_split,
        unit_lengths_by_split=unit_lengths_by_split,
        split_alignment_report=split_alignment_report,
        deep_learning_processed=deep_learning_processed,
        fit_predict_processed=fit_predict_processed,
        windowed_fit_predict_processed=windowed_fit_predict_processed,
        deep_shapes=deep_shapes,
        fit_predict_shapes=fit_predict_shapes,
        windowed_fit_predict_shapes=windowed_fit_predict_shapes,
        seq_len=seq_len,
    )


